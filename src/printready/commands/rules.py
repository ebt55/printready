"""`printready rules [--markdown]`: the profile in use, as a table, plus how each check measures it.

Every rule shows its value with a unit, whether it is Sticker Mule's published rule or our own
convention, the source page and a one-line reason. `docs/rules.md` is generated from
`render_markdown`, and a test keeps the two in sync.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

from printready.profile import Profile, ProfileError, load_profile

GENERATED_NOTE = "<!-- Generated by `printready rules --markdown`. Do not edit by hand. -->"

# How each value is written, by rule key.
UNITS = {
    "ppi_target": "{:g} PPI",
    "ppi_floor": "{:g} PPI",
    "border_in": "{:g} in",
    "border_min_in": "{:g} in",
    "min_line_pt": "{:g} pt",
    "min_text_pt": "{:g} pt",
    "cap_height_ratio": "{:g} x point size",
    "min_neck_in": "{:g} in",
    "max_upload_mb": "{:g} MB",
    "soft_alpha_max_in": "{:g} in",
    "max_bridge_border_in": "{:g} in",
    "bg_delta_e": "{:g} CIEDE2000",
    "bg_ring_uniform_frac": "{:.0%}",
    "edge_cut_min_run_in": "{:g} in",
    "speck_max_in2": "{:g} sq in",
    "damage_max_frac": "{:.0%}",
    "max_pieces": "{:g} pieces",
    "max_specks": "{:g} specks",
}

# One line per check: what it measures and which rules decide it.
CHECKS = {
    "file": "Opens the file; fails over max_upload_mb or under 64 px a side.",
    "resolution": "PPI = subject bounding box long side / (size - 2 x border_in); pass from ppi_target, "
    "warn from ppi_floor, fail below. Also reports the largest sharp size and how many px make min_line_pt.",
    "background": "Opaque art only: if bg_ring_uniform_frac of the outer 2 % ring is within bg_delta_e of one "
    "colour, the background can be removed (auto); otherwise a person.",
    "soft_alpha": "95th percentile distance from each semi-transparent pixel to the nearest opaque art pixel; "
    "warns above soft_alpha_max_in (shadow or glow: where does the cut go?).",
    "edge_crop": "Longest run of art along a canvas edge; fails above edge_cut_min_run_in (cut off), "
    "warns if shorter (pad the canvas).",
    "islands": "Art grown by border_in, holes filled, parts under speck_max_in2 ignored; more than one part fails, "
    "auto when they join within max_bridge_border_in and number at most max_pieces.",
    "text_garbled": "Vision model (optional): misspelled or garbled words fail for a person.",
    "text_small": "Vision model (optional): cap height / cap_height_ratio under min_text_pt warns.",
}

# One line per fix: which rules bound it.
FIXES = {
    "remove_background": "Flood fill from the edge within bg_delta_e; refused if more than max_pieces parts or "
    "max_specks specks remain. Guard: removed pixels farther than 2 x bg_delta_e from the background, over the "
    "kept art, must stay under damage_max_frac.",
    "add_border": "White border of border_in (never under border_min_in), waists closed with a min_neck_in circle. "
    "Guard: art pixels bit-identical.",
    "bridge_islands": "Grows the border up to max_bridge_border_in until the cut is one piece. Guard: art pixels bit-identical.",
    "pad_canvas": "Adds transparent margin for a border up to max_bridge_border_in; refused when the art is cut off. "
    "Guard: art pixels bit-identical.",
}


def _value(profile: Profile, key: str) -> str:
    return UNITS.get(key, "{:g}").format(getattr(profile, key))


def _basis(profile: Profile, key: str) -> str:
    return "convention" if profile.sources[key] == "convention" else "Sticker Mule"


def render_text(profile: Profile) -> str:
    rows = [("rule", "value", "basis", "why")]
    rows += [(key, _value(profile, key), _basis(profile, key), profile.whys[key]) for key in profile.sources]
    widths = [max(len(row[i]) for row in rows) for i in range(3)]
    lines = [f"{profile.name} ({profile.product.replace('_', '-')}): rules paraphrased from Sticker Mule's FAQ; not affiliated", ""]
    for i, row in enumerate(rows):
        lines.append("  ".join(cell.ljust(widths[j]) for j, cell in enumerate(row[:3])) + "  " + row[3])
        if i == 0:
            lines.append("  ".join("-" * w for w in widths) + "  ---")
    lines += ["", "Sources:"]
    for url in sorted({s for s in profile.sources.values() if s != "convention"}):
        keys = ", ".join(k for k, s in profile.sources.items() if s == url)
        lines.append(f"  {url}  ({keys})")
    lines += ["", "How each check measures it:"] + [f"  {c:<13} {text}" for c, text in CHECKS.items()]
    lines += ["", "How each fix uses them:"] + [f"  {f:<18} {text}" for f, text in FIXES.items()]
    return "\n".join(lines) + "\n"


def render_markdown(profile: Profile) -> str:
    lines = [
        GENERATED_NOTE,
        "",
        f"# Rules: `{profile.name}`",
        "",
        "Die-cut sticker rules paraphrased from Sticker Mule's public FAQ pages (linked per rule). Rules marked "
        "*convention* are our own choices where the FAQ gives no number. printready is not affiliated with Sticker Mule.",
        "",
        "| rule | value | basis | source | why |",
        "|---|---|---|---|---|",
    ]
    for key in profile.sources:
        source = profile.sources[key]
        link = "-" if source == "convention" else f"[FAQ]({source})"
        lines.append(f"| `{key}` | {_value(profile, key)} | {_basis(profile, key)} | {link} | {profile.whys[key]} |")
    lines += ["", "## How each check measures it", ""]
    lines += [f"- **`{c}`**: {text}" for c, text in CHECKS.items()]
    lines += ["", "## How each fix uses them", ""]
    lines += [f"- **`{f}`**: {text}" for f, text in FIXES.items()]
    return "\n".join(lines) + "\n"


def register(subparsers: argparse._SubParsersAction) -> None:
    p = subparsers.add_parser(
        "rules",
        help="show the printer rules in use and how each check measures them",
        description="Print the profile: each rule's value, Sticker Mule or convention, source and why.",
    )
    p.add_argument("--profile", type=Path, default=None, help="profile YAML (default: shipped die-cut profile)")
    p.add_argument("--markdown", action="store_true", help="print Markdown (the source of docs/rules.md)")
    p.set_defaults(func=run)


def run(args: argparse.Namespace) -> int:
    try:
        profile = load_profile(args.profile)
    except ProfileError as exc:
        print(f"rules: {exc}", file=sys.stderr)
        return 2
    sys.stdout.write(render_markdown(profile) if args.markdown else render_text(profile))
    return 0
